#!/usr/bin/env python3
"""
generate_source_tables.py

All 8 source tables for master_dataset.csv:

  PRE-EXISTING (not generated here — already in data/):
    customers.csv               — 10,000 customer profiles (dimension table)
    products.csv                — 500 product records (dimension table)

  GENERATED by this script:
    orders.csv                  — individual order transactions (~148K rows)
    order_items.csv             — line items per order (~370K rows)
    inventory_daily.csv         — daily stock position per product (365,500 rows)
    marketing_spend_daily.csv   — daily spend per channel (3,655 rows)
    website_traffic_daily.csv   — daily web traffic KPIs (731 rows)
    anomaly_log.csv             — ground-truth anomaly event labels (20 rows)

All generated table aggregates reconcile exactly with master_dataset.csv.
Run once from the project root:  python scripts/generate_source_tables.py
"""

import pandas as pd
import numpy as np
from pathlib import Path

SEED = 42
rng = np.random.default_rng(SEED)

BASE = Path(__file__).parent.parent
DATA = BASE / "data"

# ─────────────────────────────────────────────────────────────
# Load existing reference files
# ─────────────────────────────────────────────────────────────
print("=" * 60)
print("Loading master dataset and dimension tables...")
print("=" * 60)

master = pd.read_csv(DATA / "master_dataset.csv", parse_dates=["date"])
customers = pd.read_csv(DATA / "customers.csv")
products = pd.read_csv(DATA / "products.csv")

customer_ids = customers["customer_id"].to_numpy()
country_map = dict(zip(customers["customer_id"], customers["country"]))

product_ids = products["product_id"].to_numpy()   # 500 products
N_PRODUCTS = len(product_ids)

print(f"  master_dataset : {len(master):,} rows  ({master['date'].min().date()} to {master['date'].max().date()})")
print(f"  customers      : {len(customers):,} rows")
print(f"  products       : {N_PRODUCTS:,} rows")


# ─────────────────────────────────────────────────────────────
# 1. website_traffic_daily.csv  (731 rows — direct extraction)
# ─────────────────────────────────────────────────────────────
print("\n[1/6] Generating website_traffic_daily.csv...")

traffic = master[
    ["date", "sessions", "unique_visitors", "bounce_rate",
     "pages_per_session", "avg_session_duration_sec",
     "conversion_rate", "conversions_web"]
].copy()
traffic = traffic.rename(columns={"conversions_web": "conversions"})
traffic["date"] = traffic["date"].dt.strftime("%Y-%m-%d")
traffic.to_csv(DATA / "website_traffic_daily.csv", index=False)
print(f"  OK {len(traffic):,} rows  -> data/website_traffic_daily.csv")


# ─────────────────────────────────────────────────────────────
# 2. anomaly_log.csv  (~20 rows — direct extraction)
# ─────────────────────────────────────────────────────────────
print("\n[2/6] Generating anomaly_log.csv...")

anomaly_log = (
    master[master["anomaly_flag"] == 1][["date", "anomaly_event", "anomaly_kpi"]]
    .copy()
    .reset_index(drop=True)
)
anomaly_log["date"] = anomaly_log["date"].dt.strftime("%Y-%m-%d")
anomaly_log.to_csv(DATA / "anomaly_log.csv", index=False)
print(f"  OK {len(anomaly_log):,} rows  -> data/anomaly_log.csv")


# ─────────────────────────────────────────────────────────────
# 3. marketing_spend_daily.csv  (5 channels × 731 days = 3,655 rows)
# ─────────────────────────────────────────────────────────────
print("\n[3/6] Generating marketing_spend_daily.csv...")

MKTG_CHANNELS = ["paid_search", "social", "email", "affiliate", "display"]
# Stable base weights per channel; Dirichlet adds per-day variation
BASE_WEIGHTS = np.array([0.35, 0.25, 0.20, 0.12, 0.08])

mktg_rows = []
for _, row in master.iterrows():
    date_str = row["date"].strftime("%Y-%m-%d")

    # Per-day channel weights (sum to 1, vary slightly around base)
    weights = rng.dirichlet(BASE_WEIGHTS * 15)

    total_spend    = float(row["total_spend_usd"])
    total_impr     = int(row["total_impressions"])
    total_clicks   = int(row["total_clicks"])
    total_conv     = int(row["total_conversions_marketing"])
    total_attr_rev = float(row["total_attributed_revenue_usd"])

    # Allocate each metric across channels; fix last channel so sums are exact
    spend_alloc = (weights * total_spend).round(2)
    spend_alloc[-1] = round(total_spend - spend_alloc[:-1].sum(), 2)

    impr_alloc = (weights * total_impr).astype(int)
    impr_alloc[-1] = total_impr - impr_alloc[:-1].sum()

    click_alloc = (weights * total_clicks).astype(int)
    click_alloc[-1] = total_clicks - click_alloc[:-1].sum()

    conv_alloc = (weights * total_conv).astype(int)
    conv_alloc[-1] = total_conv - conv_alloc[:-1].sum()

    rev_alloc = (weights * total_attr_rev).round(2)
    rev_alloc[-1] = round(total_attr_rev - rev_alloc[:-1].sum(), 2)

    for i, ch in enumerate(MKTG_CHANNELS):
        spend = max(float(spend_alloc[i]), 0.01)
        rev   = float(rev_alloc[i])
        mktg_rows.append({
            "date": date_str,
            "channel": ch,
            "spend_usd": round(spend, 2),
            "impressions": max(int(impr_alloc[i]), 0),
            "clicks": max(int(click_alloc[i]), 0),
            "conversions": max(int(conv_alloc[i]), 0),
            "attributed_revenue_usd": round(rev, 2),
            "roas": round(rev / spend, 3),
        })

mktg_df = pd.DataFrame(mktg_rows)
mktg_df.to_csv(DATA / "marketing_spend_daily.csv", index=False)
print(f"  OK {len(mktg_df):,} rows  -> data/marketing_spend_daily.csv")


# ─────────────────────────────────────────────────────────────
# 4. inventory_daily.csv  (500 products × 731 days = 365,500 rows)
# ─────────────────────────────────────────────────────────────
print("\n[4/6] Generating inventory_daily.csv  (500 × 731 = 365,500 rows)...")

inv_frames = []
for _, row in master.iterrows():
    date_str    = row["date"].strftime("%Y-%m-%d")
    total_stock = int(row["total_stock_on_hand"])
    total_sold  = int(row["total_units_sold"])
    n_stockouts = min(int(row["n_stockouts"]), N_PRODUCTS)
    n_reorders  = min(int(row["n_reorders"]), N_PRODUCTS)

    # Decide which products are stocked out
    stockout_idx = set(rng.choice(N_PRODUCTS, size=n_stockouts, replace=False).tolist())
    non_stockout = [i for i in range(N_PRODUCTS) if i not in stockout_idx]

    # Reorders preferentially on stockout products first
    reorder_pool = list(stockout_idx) + non_stockout
    reorder_idx  = set(reorder_pool[:n_reorders])

    # Distribute stock only among non-stockout products
    if non_stockout:
        sw = rng.dirichlet(np.ones(len(non_stockout)))
        stock_vals = (sw * total_stock).astype(int)
        stock_vals[-1] = max(total_stock - int(stock_vals[:-1].sum()), 0)
        stock_by_i = dict(zip(non_stockout, stock_vals.tolist()))
    else:
        stock_by_i = {}

    # Distribute units_sold across all products
    sold_w = rng.dirichlet(np.ones(N_PRODUCTS))
    sold_vals = (sold_w * total_sold).astype(int)
    sold_vals[-1] = max(total_sold - int(sold_vals[:-1].sum()), 0)

    day_df = pd.DataFrame({
        "date":              date_str,
        "product_id":        product_ids,
        "stock_on_hand":     [stock_by_i.get(i, 0) for i in range(N_PRODUCTS)],
        "units_sold":        sold_vals.tolist(),
        "reorder_triggered": [1 if i in reorder_idx  else 0 for i in range(N_PRODUCTS)],
        "stockout_flag":     [1 if i in stockout_idx else 0 for i in range(N_PRODUCTS)],
    })
    inv_frames.append(day_df)

inv_df = pd.concat(inv_frames, ignore_index=True)
inv_df.to_csv(DATA / "inventory_daily.csv", index=False)
print(f"  OK {len(inv_df):,} rows  -> data/inventory_daily.csv")


# ─────────────────────────────────────────────────────────────
# 5. orders.csv  (~142,000 rows)
# ─────────────────────────────────────────────────────────────
print("\n[5/6] Generating orders.csv...")

ORDER_CHANNELS = ["organic_search", "paid_search", "email", "social",
                  "direct", "affiliate", "referral"]
CHANNEL_PROBS  = np.array([0.30, 0.20, 0.18, 0.12, 0.10, 0.06, 0.04])

order_rows  = []
order_id_seq = 1

for _, row in master.iterrows():
    date_str  = row["date"].strftime("%Y-%m-%d")
    n_orders  = int(row["n_orders"])
    total_rev = float(row["total_revenue_usd"])
    disc      = float(row["avg_discount_pct"])
    n_unique  = min(int(row["n_unique_customers"]), n_orders)
    n_returns = min(int(row["n_returns"]), n_orders)

    # ── Customer assignment ──────────────────────────────────
    # Pick n_unique distinct customers; fill remaining orders from repeats
    chosen_unique = rng.choice(customer_ids, size=n_unique, replace=False)
    extra = n_orders - n_unique
    if extra > 0:
        repeats   = rng.choice(chosen_unique, size=extra, replace=True)
        all_custs = np.concatenate([chosen_unique, repeats])
    else:
        all_custs = chosen_unique.copy()
    rng.shuffle(all_custs)

    # ── Revenue split ────────────────────────────────────────
    rev_w  = rng.dirichlet(np.ones(n_orders))
    rev_split = (rev_w * total_rev).round(2)
    rev_split[-1] = round(total_rev - float(rev_split[:-1].sum()), 2)

    # ── Statuses: exactly n_returns = 'returned', rest 'completed' ──
    statuses = np.array(["completed"] * n_orders, dtype=object)
    if n_returns > 0:
        ret_idx = rng.choice(n_orders, size=n_returns, replace=False)
        statuses[ret_idx] = "returned"

    # ── Channels ─────────────────────────────────────────────
    channels = rng.choice(ORDER_CHANNELS, size=n_orders, p=CHANNEL_PROBS)

    for j in range(n_orders):
        cust = all_custs[j]
        order_rows.append({
            "order_id":        f"O{order_id_seq:09d}",
            "customer_id":     cust,
            "order_date":      date_str,
            "channel":         channels[j],
            "status":          statuses[j],
            "order_total_usd": max(float(rev_split[j]), 0.01),
            "discount_pct":    disc,
            "country":         country_map.get(cust, "US"),
        })
        order_id_seq += 1

orders_df = pd.DataFrame(order_rows)
orders_df.to_csv(DATA / "orders.csv", index=False)
print(f"  OK {len(orders_df):,} rows  -> data/orders.csv")


# ─────────────────────────────────────────────────────────────
# 6. order_items.csv  (~400,000 rows — 1-4 items per order)
# ─────────────────────────────────────────────────────────────
print("\n[6/6] Generating order_items.csv  (1–4 items per order)...")

item_rows   = []
item_id_seq = 1

for _, order in orders_df.iterrows():
    n_items   = int(rng.integers(1, 5))          # 1, 2, 3, or 4 items
    order_tot = float(order["order_total_usd"])
    disc      = float(order["discount_pct"])

    chosen_prods = rng.choice(product_ids, size=n_items, replace=False)
    quantities   = rng.integers(1, 4, size=n_items)  # 1–3 units each

    # Split order total across line items
    lw = rng.dirichlet(np.ones(n_items))
    line_totals = (lw * order_tot).round(2)
    line_totals[-1] = round(order_tot - float(line_totals[:-1].sum()), 2)

    for k in range(n_items):
        qty        = int(quantities[k])
        line_total = max(float(line_totals[k]), 0.01)
        unit_price = round(line_total / qty, 2)
        item_rows.append({
            "order_item_id":  f"OI{item_id_seq:010d}",
            "order_id":       order["order_id"],
            "product_id":     chosen_prods[k],
            "quantity":       qty,
            "unit_price_usd": unit_price,
            "discount_pct":   disc,
            "line_total_usd": line_total,
        })
        item_id_seq += 1

items_df = pd.DataFrame(item_rows)
items_df.to_csv(DATA / "order_items.csv", index=False)
print(f"  OK {len(items_df):,} rows  -> data/order_items.csv")


# ─────────────────────────────────────────────────────────────
# Summary
# ─────────────────────────────────────────────────────────────
print("\n" + "=" * 60)
print("All 8 source tables present in data/")
print("=" * 60)
print("  PRE-EXISTING (dimension tables):")
print(f"  customers             : {len(customers):>10,} rows  (read-only)")
print(f"  products              : {N_PRODUCTS:>10,} rows  (read-only)")
print()
print("  GENERATED (fact + label tables):")
print(f"  website_traffic_daily : {len(traffic):>10,} rows")
print(f"  anomaly_log           : {len(anomaly_log):>10,} rows")
print(f"  marketing_spend_daily : {len(mktg_df):>10,} rows")
print(f"  inventory_daily       : {len(inv_df):>10,} rows")
print(f"  orders                : {len(orders_df):>10,} rows")
print(f"  order_items           : {len(items_df):>10,} rows")
print("=" * 60)
